async def export(session, repo, out, **kwargs):
    return await run_export(session, repo, Path(out), **kwargs)


# ---- happy path ----------------------------------------------------------


async def test_export_writes_context_and_adr(session, seeded_kb, tmp_path):
    result = await export(session, seeded_kb, tmp_path)
    assert result.conflicts == [] and result.failed == []

    context = (tmp_path / CONTEXT).read_text()
    assert "## Language" in context
    assert "**Order**:\nA customer's request for goods.\n_Avoid_: Purchase, transaction" in context
    assert "**Invoice**:" in context

    adr = (tmp_path / "docs/adr/0001-use-postgres.md").read_text()
    assert adr.startswith("<!-- generated by cartograph;")
    assert "# 0001. Use Postgres" in adr
    assert (tmp_path / MANIFEST_NAME).is_file()


async def test_export_is_byte_identical_on_rerun(session, seeded_kb, tmp_path):
    await export(session, seeded_kb, tmp_path)
    before = {p: p.read_bytes() for p in tmp_path.rglob("*") if p.is_file()}

    second = await export(session, seeded_kb, tmp_path)
    after = {p: p.read_bytes() for p in tmp_path.rglob("*") if p.is_file()}

    assert before == after
    assert second.written == []
    assert CONTEXT in second.unchanged


