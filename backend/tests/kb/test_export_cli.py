async def test_archiving_an_entry_prunes_its_file(session, seeded_kb, tmp_path):
    await export(session, seeded_kb, tmp_path)
    adr = tmp_path / "docs/adr/0001-use-postgres.md"
    assert adr.is_file()

    entry = await q_kb.get_entry_by_slug(session, "use-postgres", type="decision")
