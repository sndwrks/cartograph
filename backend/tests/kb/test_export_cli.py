# ---- manifest integrity (review findings 1, 5, 22, 23) -------------------


async def test_manifest_is_rewritten_even_when_nothing_changed(
    session, seeded_kb, tmp_path
):
    """A lost manifest must come back, or the marker fallback silently
    overwrites hand edits forever."""
    await export(session, seeded_kb, tmp_path)
    (tmp_path / MANIFEST_NAME).unlink()

    result = await export(session, seeded_kb, tmp_path)  # every file unchanged
    assert result.written == []
    assert (tmp_path / MANIFEST_NAME).is_file()

    # and now a hand edit is detected rather than clobbered
    target = tmp_path / "docs/adr/0001-use-postgres.md"
    target.write_text(target.read_text() + "\nMine.\n")
    after = await export(session, seeded_kb, tmp_path)
    assert "docs/adr/0001-use-postgres.md" in after.conflicts
    assert "Mine." in target.read_text()


async def test_prune_refuses_paths_outside_the_output_directory(
    session, seeded_kb, tmp_path
):
    """The manifest is repo content, so its keys are no more trusted than any
    other repo content — and pruning DELETES."""
    outside = tmp_path.parent / "victim.txt"
    outside.write_text("do not delete me\n")

    await export(session, seeded_kb, tmp_path)
    manifest = json.loads((tmp_path / MANIFEST_NAME).read_text())
    manifest["files"]["../victim.txt"] = {
        "sha256": hashlib.sha256(outside.read_bytes()).hexdigest(),
        "type": "glossary",
    }
    manifest["files"][str(tmp_path.parent / "victim.txt")] = {
        "sha256": hashlib.sha256(outside.read_bytes()).hexdigest(),
        "type": "glossary",
    }
    (tmp_path / MANIFEST_NAME).write_text(json.dumps(manifest))

    result = await export(session, seeded_kb, tmp_path)
    assert outside.exists(), "prune escaped the output directory"
    assert any("unsafe manifest path" in f["error"] for f in result.failed)


