"""The KB type layer — pure, no database."""

import random
from pathlib import PurePosixPath

import pytest
from pydantic import ValidationError

from cartograph.kb.types import (
    LOOKUP_PRECEDENCE,
    REGISTRY,
    Decision,
    Glossary,
    UnknownKbTypeError,
    get_type,
    type_rank,
    types_with_lookup_key,
)
from cartograph.kb.types.base import LOOKUP_KEYS
from conftest import make_view


# ---- registry ------------------------------------------------------------


def test_registry_names_match_keys():
    assert all(name == kb_type.name for name, kb_type in REGISTRY.items())
    assert set(REGISTRY) == set(LOOKUP_PRECEDENCE)


def test_registry_lookup_keys_are_valid():
    for kb_type in REGISTRY.values():
        assert kb_type.lookup_keys
        assert set(kb_type.lookup_keys) <= set(LOOKUP_KEYS)


def test_every_type_exports_relative_paths(ctx):
    for name, kb_type in REGISTRY.items():
        view = make_view(name, "sample", "Sample", seq=1)
        for path in kb_type.export([view], ctx):
            assert not path.is_absolute()
            assert ".." not in path.parts


def test_unknown_type_raises():
    with pytest.raises(UnknownKbTypeError) as exc:
        get_type("adr")
    assert "adr" in str(exc.value)


def test_types_with_lookup_key_is_precedence_ordered():
    assert types_with_lookup_key("aliases") == ("glossary", "convention")
    assert type_rank("glossary") == 0
    assert type_rank("nope") == len(LOOKUP_PRECEDENCE)


# ---- embed text ----------------------------------------------------------


def test_glossary_embed_text_matches_legacy_format():
    """The pre-typed-KB f-string, byte for byte.

    If this changes, every embedding written before the typed-KB migration is
    silently invalidated and has to be re-paid for at Voyage.
    """
    view = make_view("glossary", "psn", "PSN", "PositageNet")
    assert Glossary.embed_text(view) == "PSN: PositageNet"
    assert Glossary.embed_text(view) == f"{view.title}: {view.body}"


def test_decision_embed_text_includes_context_and_consequences():
    view = make_view(
        "decision",
        "flat-threads",
        "Flat threads",
        "Re-parent replies to the root.",
        payload={"context": "Threads nested arbitrarily.", "consequences": "Two levels only."},
        seq=1,
    )
    text = Decision.embed_text(view)
    assert "Threads nested arbitrarily." in text
    assert "Two levels only." in text
    assert text != f"{view.title}: {view.body}"


