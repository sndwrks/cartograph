# ---- glossary export -----------------------------------------------------


def glossary_entries():
    return [
        make_view(
            "glossary",
            "order",
            "Order",
            "A customer's request for goods.",
            payload={"avoid": ["Purchase", "transaction"]},
        ),
        make_view("glossary", "invoice", "Invoice", "A request for payment.", entry_id=2),
    ]


def test_glossary_export_pocock_format(ctx):
    [(path, content)] = Glossary.export(glossary_entries(), ctx).items()
    assert path == PurePosixPath("CONTEXT.md")
    assert content.startswith("<!-- generated by cartograph;")
    assert "# Acme" in content
    assert "## Language" in content
    assert "**Order**:\nA customer's request for goods.\n_Avoid_: Purchase, transaction" in content


def test_glossary_export_omits_avoid_line_when_empty(ctx):
    [content] = Glossary.export(glossary_entries(), ctx).values()
    invoice = content.split("**Invoice**:")[1]
    assert "_Avoid_" not in invoice


def test_glossary_export_is_stable_and_order_independent(ctx):
    entries = glossary_entries()
    baseline = Glossary.export(sorted(entries, key=Glossary.sort_key), ctx)
    for _ in range(5):
        shuffled = entries[:]
        random.shuffle(shuffled)
        assert Glossary.export(sorted(shuffled, key=Glossary.sort_key), ctx) == baseline


# ---- other types ---------------------------------------------------------


def test_decision_export_filename_is_zero_padded(ctx):
    view = make_view("decision", "use-postgres", "Use Postgres", seq=1)
    [path] = Decision.export([view], ctx)
    assert path == PurePosixPath("docs/adr/0001-use-postgres.md")


def test_decision_export_renders_status_and_consequences(ctx):
    view = make_view(
        "decision",
        "use-postgres",
        "Use Postgres",
        "We use Postgres.",
        payload={
            "decision_status": "superseded",
            "context": "We needed a database.",
            "consequences": "One dependency.",
            "deciders": ["john"],
        },
        seq=7,
    )
    [content] = Decision.export([view], ctx).values()
    assert "# 0007. Use Postgres" in content
    assert "- Status: superseded" in content
    assert "- Deciders: john" in content
    assert "## Context\n\nWe needed a database." in content
    assert "## Consequences\n\nOne dependency." in content


def test_decision_sorts_by_seq_not_title(ctx):
    late = make_view("decision", "aaa", "AAA", seq=9)
    early = make_view("decision", "zzz", "ZZZ", seq=1, entry_id=2)
    assert sorted([late, early], key=Decision.sort_key) == [early, late]


def test_decision_without_seq_is_a_loud_error(ctx):
    with pytest.raises(ValueError, match="no seq"):
        Decision.export([make_view("decision", "x", "X")], ctx)


def test_specification_export_one_file_per_entry(ctx):
    spec = REGISTRY["specification"]
    views = [
        make_view("specification", "board", "Board protocol", payload={"requirements": ["A", "B"]}),
        make_view("specification", "ingest", "Ingest", entry_id=2),
    ]
    out = spec.export(views, ctx)
    assert set(out) == {
        PurePosixPath("docs/spec/board.md"),
        PurePosixPath("docs/spec/ingest.md"),
    }
    assert "- A\n- B" in out[PurePosixPath("docs/spec/board.md")]


def test_runbook_export_numbers_steps(ctx):
    view = make_view(
        "runbook",
        "rotate-key",
        "Rotate the Voyage key",
        payload={"steps": ["Revoke", "Issue", "Redeploy"], "severity": "high"},
    )
    [content] = REGISTRY["runbook"].export([view], ctx).values()
    assert "- Severity: high" in content
    assert "1. Revoke\n2. Issue\n3. Redeploy" in content


def test_convention_export_renders_examples(ctx):
    view = make_view(
        "convention",
        "branch-names",
        "Branch names",
        payload={
            "applies_to": ["*"],
            "rationale": "main is protected.",
            "examples": [{"good": "main.feature", "bad": "feature", "note": "Always prefix."}],
        },
    )
    [content] = REGISTRY["convention"].export([view], ctx).values()
    assert "## Rationale\n\nmain is protected." in content
    assert "Do:" in content and "main.feature" in content
    assert "Avoid:" in content and "Always prefix." in content


@pytest.mark.parametrize("name", sorted(REGISTRY))
def test_export_files_end_with_exactly_one_newline(ctx, name):
    view = make_view(name, "sample", "Sample", seq=1)
    for content in REGISTRY[name].export([view], ctx).values():
        assert content.endswith("\n")
        assert not content.endswith("\n\n")


# ---- lint ----------------------------------------------------------------


def test_glossary_lints_an_over_long_definition():
    short = make_view("glossary", "psn", "PSN", "PositageNet. Never anything else.")
    assert Glossary.validate_entry(short) == []
    rambling = make_view("glossary", "psn", "PSN", "One. Two. Three. Four.")
    assert Glossary.validate_entry(rambling)
